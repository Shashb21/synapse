import { expect, test } from "@playwright/test";
import { freshWorkspace } from "../support/session";
import { iegpAction, planAction, planState, runStage, validateBandHigh } from "../support/synapse";

let gapId = "";
freshWorkspace({ name: "KAN136 option audit", seed: async request => {
  const gap = await iegpAction(request, { action: "create_gap", name: "Routine care outcome decision", statement: "Comparative routine care outcomes are missing", domain: "economics" });
  gapId = String(gap.id);
  await iegpAction(request, { action: "validate_gap", gap_id: gapId });
  await validateBandHigh(request, gapId, "This comparison blocks the current dossier");
  await runStage(request, "S9", { gap_ids: [gapId], per_gap: 3 });
} });

test("supported accept/reject decisions, recovery, lifecycle and manual dates persist in shared history", async ({ page, request }, testInfo) => {
  test.setTimeout(90_000);
  page.setDefaultTimeout(15_000);
  const pending = (await planState(request)).proposals.filter(row => row.gap_id === gapId && row.status === "proposed");
  expect(pending).toHaveLength(3);
  await page.goto("/ideation");
  const card = (id: number) => page.locator("article").filter({ has: page.getByRole("heading", { name: pending[id].name, exact: true }) }).first();
  await expect(card(0).getByRole("list", { name: "Option supporting references" })).toContainText("Routine care outcome decision");
  await card(0).getByRole("button", { name: `Accept ${pending[0].name}`, exact: true }).click();
  const accept = page.getByRole("dialog", { name: `Accept ${pending[0].name}`, exact: true });
  await accept.getByRole("button", { name: "Accept proposal", exact: true }).click();
  await expect(accept.getByRole("alert")).toContainText("rationale");
  await accept.getByLabel("Rationale (required)").fill("The comparative cohort is a feasible first option");
  await page.route("**/api/plan", route => route.fulfill({ status: 500, contentType: "application/json", body: JSON.stringify({ safe_error: true, request_outcome: "rejected", error: "The proposal could not be accepted. Review your rationale and try again." }) }), { times: 1 });
  await accept.getByRole("button", { name: "Accept proposal", exact: true }).click();
  await expect(accept.getByRole("alert")).toContainText("The proposal could not be accepted. Review your rationale and try again.");
  await expect(accept.getByLabel("Rationale (required)")).toHaveValue("The comparative cohort is a feasible first option");
  await accept.getByRole("button", { name: "Accept proposal", exact: true }).click();
  await expect(accept).toBeHidden();
  await expect(card(0)).toContainText("Accepted by");
  await card(1).getByRole("button", { name: `Reject ${pending[1].name}`, exact: true }).click();
  const reject = page.getByRole("dialog", { name: `Reject ${pending[1].name}`, exact: true });
  await reject.getByLabel("Rationale (required)").fill("Data access is insufficient for this alternative");
  await reject.getByRole("button", { name: "Reject proposal", exact: true }).click();
  await expect(reject).toBeHidden();
  await expect(card(1)).toContainText("Rejected by");
  await expect(card(2)).toContainText("Proposed");
  const accepted = (await planState(request)).proposals.find(row => row.id === pending[0].id)!;
  const tacticId = String(accepted.tactic_id);
  await page.goto(`/tactics/${tacticId}`);
  await page.getByRole("button", { name: "Edit tactic", exact: true }).click();
  const editor = page.getByRole("form", { name: `Edit ${pending[0].name}`, exact: true });
  await editor.getByRole("combobox", { name: "Status", exact: true }).selectOption("planned");
  await editor.getByLabel("Start date", { exact: true }).fill("2027-01");
  await editor.getByLabel("Why? (required)").fill("Funding approved and the January start date is agreed");
  await editor.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(editor).toBeHidden();
  await page.getByRole("group", { name: "History", exact: true }).locator("summary").first().click();
  const history = page.getByTestId("entity-history");
  await expect(history).toContainText("The comparative cohort is a feasible first option");
  await expect(history).toContainText("Funding approved and the January start date is agreed");
  await expect(history.getByRole("list", { name: "Decision supporting references" }).first()).toContainText("Routine care outcome decision");
  await history.screenshot({ path: testInfo.outputPath("tactic-option-history.png") });
  await page.goto(`/gaps/${gapId}`);
  await expect(page.getByTestId("gap-ideas")).toContainText("accepted");
  await expect(page.getByTestId("gap-ideas")).toContainText("rejected");
  await expect(page.getByTestId("gap-ideas")).toContainText("proposed");
  await expect(page.getByTestId("entity-history")).toContainText("Data access is insufficient for this alternative");
  const gap = await (await request.get(`/api/gaps/${gapId}`)).json();
  const tactic = await (await request.get(`/api/tactics/${tacticId}`)).json();
  const acceptance = gap.history.find((row: { entity_id: string; action: string }) => row.entity_id === pending[0].id && row.action === "accept");
  expect(tactic.history.some((row: { id: string }) => row.id === acceptance.id)).toBe(true);
  expect(tactic.tactic).toMatchObject({ status: "planned", start_date: "2027-01" });
});

test("a stale option dialog retains its original selection and reason", async ({ page, request }) => {
  page.setDefaultTimeout(15_000);
  // The preceding acceptance changes that gap's context. Start with a current
  // proposal so this case isolates a concurrent proposal edit, not context review.
  const gap = await iegpAction(request, { action: "create_gap", name: "Concurrent option review", statement: "Comparative outcomes need a separate review", domain: "economics" });
  const reviewGapId = String(gap.id);
  await iegpAction(request, { action: "validate_gap", gap_id: reviewGapId });
  await validateBandHigh(request, reviewGapId, "This comparison needs an independent option decision");
  await runStage(request, "S9", { gap_ids: [reviewGapId], per_gap: 1 });
  const pending = (await planState(request)).proposals.find(row => row.gap_id === reviewGapId && row.status === "proposed")!;
  await page.goto("/ideation");
  const card = page.locator("article").filter({ has: page.getByRole("heading", { name: pending.name, exact: true }) }).filter({ has: page.getByRole("button", { name: `Accept ${pending.name}`, exact: true }) }).first();
  await card.getByRole("button", { name: `Accept ${pending.name}`, exact: true }).click();
  const dialog = page.getByRole("dialog", { name: `Accept ${pending.name}`, exact: true });
  await dialog.getByLabel("Decision basis").selectOption("manual");
  await dialog.getByLabel("Rationale (required)").fill("Retain my explicit manual option decision");
  await planAction(request, { action: "edit_proposal", id: pending.id, expected_version: pending.version, name: "Concurrently corrected option", rationale: "Corrected by a second reviewer" });
  await dialog.getByRole("button", { name: "Accept proposal", exact: true }).click();
  await expect(dialog.getByRole("alert")).toContainText("Proposal changed");
  await expect(dialog.getByLabel("Decision basis")).toHaveValue("manual");
  await expect(dialog.getByLabel("Rationale (required)")).toHaveValue("Retain my explicit manual option decision");
  expect((await planState(request)).proposals.find(row => row.id === pending.id)?.status).toBe("proposed");
});

test("timeline tactic detail edits send the opening token and retain a stale draft", async ({ page, request }) => {
  test.setTimeout(90_000);
  page.setDefaultTimeout(15_000);
  const created = await iegpAction(request, { action: "record_missed_tactic", name: "Review round timeline cohort", type: "rwe_study", status: "planned", evidence_question: "What outcomes occur in routine care?" });
  const tacticId = String(created.id);
  await planAction(request, { action: "add_activity", tactic_id: tacticId, start_date: "2026-11-01", end_date: "2027-02-01", rationale: "Schedule the reviewed routine care cohort" });
  const opening = await (await request.get(`/api/tactics/${tacticId}`)).json();
  await page.goto("/timeline");
  await page.locator('g[aria-label*="Review round timeline cohort"]').first().click();
  const panel = page.getByRole("dialog");
  await panel.getByRole("button", { name: "Edit", exact: true }).click();
  const form = panel.getByTestId("activity-editor");
  await form.getByLabel("Budget", { exact: true }).fill("$250K");
  await form.getByLabel("Rationale for the change").fill("Budget reviewed from the timeline opening");
  const posted = page.waitForRequest(request => request.url().endsWith("/api/iegp") && request.method() === "POST");
  await form.getByRole("button", { name: "Save changes", exact: true }).click();
  expect((await posted).postDataJSON().expected_tactic).toBe(opening.version);
  await expect(form).toBeHidden();
  await expect(panel).toContainText("$250K");
  await panel.getByRole("button", { name: "Edit", exact: true }).click();
  await form.getByLabel("Budget", { exact: true }).fill("$500K");
  await form.getByLabel("Rationale for the change").fill("Keep this earlier budget decision and explanation");
  const latest = await (await request.get(`/api/tactics/${tacticId}`)).json();
  await iegpAction(request, { action: "modify_tactic", tactic_id: tacticId, expected_tactic: latest.version, budget: "$400K", rationale: "A second reviewer corrected the cohort budget" });
  await form.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(form.getByRole("alert")).toContainText("Tactic changed");
  await expect(form.getByLabel("Budget", { exact: true })).toHaveValue("$500K");
  await expect(form.getByLabel("Rationale for the change")).toHaveValue("Keep this earlier budget decision and explanation");
  const saved = await (await request.get(`/api/tactics/${tacticId}`)).json();
  expect(saved.tactic.budget).toBe("$400K");
  expect(saved.history.some((entry: { rationale: string }) => entry.rationale === "Keep this earlier budget decision and explanation")).toBe(false);
});
