/** Four-step Development workflow against isolated persistence and scripted execution I/O. */
import { expect, test } from "@playwright/test";
import { developmentDetails, developmentStep } from "../support/development-workflow";

const artifact = ".superpowers/sdd/2026-11-03-ui-2-development-workflow";
test("documents, settings, run and results preserve edits and derive the next action from saved work", async ({ page }) => {
  let saved: Record<string, unknown> | null = null;
  let posts = 0;
  let reads = 0;
  await page.route("**/api/admin/development/*/executions**", async route => {
    if (route.request().method() === "POST") {
      posts++;
      const body = route.request().postDataJSON();
      saved = { id: "workflow-saved-run", experiment_id: "fixture", created_at: "2026-11-03", updated_at: "2026-11-03", generation_status: "succeeded", evaluation_status: "not_requested", error: null, manifest: { revision: body.revision, config: body.config, routes: {} }, sections: [], calls: [] };
      await route.fulfill({ status: 202, json: { execution: saved } });
    } else {
      reads++;
      await route.fulfill({ json: { executions: saved ? [saved] : [], delivery: { available: true, reason: null } } });
    }
  });
  const name = `Workflow ${Date.now()}`;
  await page.goto("/admin/development");
  await page.getByLabel("New experiment name").fill(name);
  await page.getByRole("button", { name: "Create experiment" }).click();
  const nav = page.getByRole("navigation", { name: "Experiment workflow" });
  await expect(nav.getByRole("button", { name: /^1\. Documents/ })).toHaveAttribute("aria-current", "step");
  await expect(page.getByLabel("Next action")).toContainText("Add and save a source document");
  await page.getByLabel("Private source file").setInputFiles({ name: "workflow.txt", mimeType: "text/plain", buffer: Buffer.from("Comparative evidence remains uncertain.") });
  await page.getByLabel("Experiment name", { exact: true }).fill(`${name} edited`);
  await nav.getByRole("button", { name: /^1\. Documents/ }).focus();
  await page.keyboard.press("Tab");
  await expect(nav.getByRole("button", { name: /^2\. Test settings/ })).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(nav.getByRole("button", { name: /^2\. Test settings/ })).toBeFocused();
  await expect(nav.getByRole("button", { name: /^2\. Test settings/ })).toHaveAttribute("aria-current", "step");
  await page.getByLabel("Execution mode").selectOption("single_pass");
  await page.getByText("Gap extraction route and roles", { exact: true }).click();
  const gap = page.getByText("Gap extraction route and roles", { exact: true }).locator("..");
  const model = gap.getByRole("combobox", { name: "Model", exact: true }).first();
  await expect(model).toBeVisible();
  await expect(model.locator("option").last()).toBeAttached();
  const modelOptions = await model.locator("option").allTextContents();
  await model.selectOption(modelOptions[modelOptions.length - 1]);
  await gap.getByLabel("Temperature", { exact: true }).first().fill("0.37");
  await expect(gap.getByLabel("Critic override", { exact: true })).toBeDisabled();
  await developmentDetails(page, "Legacy evaluator route");
  await developmentStep(page, "Documents");
  await expect(page.getByLabel("Private source file")).toHaveValue(/workflow.txt/);
  await expect(page.getByLabel("Experiment name", { exact: true })).toHaveValue(`${name} edited`);
  await page.getByRole("button", { name: "Upload source", exact: true }).click();
  await expect(page.getByText("workflow.txt", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Next action")).toContainText("Review test settings");
  await expect(nav.getByRole("button", { name: /^2\. Test settings/ })).toContainText("Not started");
  await developmentDetails(page, "Optional evaluation references");
  await expect(page.getByLabel("Reference PDF", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Save name", exact: true }).click();
  const settingsShortcut = page.getByRole("button", { name: "Go to Test settings", exact: true });
  await settingsShortcut.focus();
  await page.keyboard.press("Enter");
  const settingsNavigation = nav.getByRole("button", { name: /^2\. Test settings/ });
  await expect(settingsShortcut).toHaveCount(0);
  await expect(settingsNavigation).toBeFocused();
  await expect(settingsNavigation).toBeVisible();
  await expect(settingsNavigation).toHaveCSS("outline-style", "solid");
  await page.keyboard.press("Tab");
  await expect(nav.getByRole("button", { name: /^3\. Run/ })).toBeFocused();
  await expect(page.getByLabel("Execution mode")).toHaveValue("single_pass");
  await expect(gap.getByLabel("Temperature", { exact: true }).first()).toHaveValue("0.37");
  await expect(model).toHaveValue(modelOptions[modelOptions.length - 1]);
  // Step movement itself must not mutate or refetch execution state.
  await page.waitForTimeout(500);
  const readsBeforeNavigation = reads;
  await developmentStep(page, "Results");
  await expect(page.getByRole("region", { name: "Saved comparison" })).toBeVisible();
  await expect(page.getByRole("region", { name: "Evaluation", exact: true })).toBeVisible();
  await developmentStep(page, "Run");
  await expect(page.getByRole("button", { name: "Preview generation cost" })).toBeVisible();
  expect(reads).toBe(readsBeforeNavigation);
  expect(posts).toBe(0);
  const runButton = page.getByRole("button", { name: "Run all sections", exact: true });
  await runButton.focus();
  await page.keyboard.press("Enter");
  await expect(page.getByLabel("Next action")).toContainText("Review saved outputs");
  // Background history updates change guidance without moving the selected step.
  await expect(nav.getByRole("button", { name: /^3\. Run/ })).toHaveAttribute("aria-current", "step");
  const resultsShortcut = page.getByRole("button", { name: "Go to Results", exact: true });
  await resultsShortcut.focus();
  await page.keyboard.press("Enter");
  const resultsNavigation = nav.getByRole("button", { name: /^4\. Results/ });
  await expect(resultsShortcut).toHaveCount(0);
  await expect(resultsNavigation).toBeFocused();
  await expect(resultsNavigation).toBeVisible();
  await expect(resultsNavigation).toHaveCSS("outline-style", "solid");
  await page.keyboard.press("Tab");
  await expect(page.getByRole("button", { name: "Reload history", exact: true })).toBeFocused();
  await expect(nav.getByRole("button", { name: /^3\. Run/ })).toContainText("Complete");
  await expect(page.getByText("Generation: succeeded · 0/0 sections finished")).toBeVisible();
  expect(posts).toBe(1);
  await page.reload();
  await page.getByRole("button", { name: `Open ${name} edited`, exact: true }).click();
  await expect(nav.getByRole("button", { name: /^4\. Results/ })).toHaveAttribute("aria-current", "step");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: `${artifact}/workflow-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${artifact}/workflow-mobile.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  // A 720 CSS-pixel viewport is the reflow equivalent of 200% zoom on a 1440px display.
  await page.setViewportSize({ width: 720, height: 500 });
  await developmentStep(page, "Test settings");
  await developmentDetails(page, "Gap extraction route and roles");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `${artifact}/workflow-200-percent-reflow.png`, fullPage: true });
});

test("reopened source-only draft chooses settings and failed history offers recovery without claiming no runs", async ({ page, request }) => {
  const name = `Workflow recovery ${Date.now()}`;
  const created = await (await request.post("/api/admin/development", { data: { name, source_workspace_id: null } })).json();
  const draft = (await (await request.post(`/api/admin/development/${created.experiment.id}/source-upload`, { data: { revision: created.experiment.revision, filename: "saved.txt", content_base64: Buffer.from("Saved source").toString("base64") } })).json()).experiment;
  let unavailable = false;
  await page.route(`**/api/admin/development/${draft.id}/executions**`, route => unavailable ? route.fulfill({ status: 503, json: { error: "History unavailable" } }) : route.fulfill({ json: { executions: [], delivery: { available: true, reason: null } } }));
  await page.goto("/admin/development");
  await page.getByRole("button", { name: `Open ${name}`, exact: true }).click();
  const nav = page.getByRole("navigation", { name: "Experiment workflow" });
  await expect(nav.getByRole("button", { name: /^2\. Test settings/ })).toHaveAttribute("aria-current", "step");
  unavailable = true;
  await page.reload();
  await page.getByRole("button", { name: `Open ${name}`, exact: true }).click();
  await expect(nav.getByRole("button", { name: /^4\. Results/ })).toHaveAttribute("aria-current", "step");
  await expect(page.getByLabel("Next action")).toContainText("Reload history");
  await expect(page.getByText("No executions yet.")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Reload history", exact: true })).toBeEnabled();
  unavailable = false;
  await page.getByRole("button", { name: "Reload history", exact: true }).click();
  await expect(page.getByLabel("Next action")).toContainText("Review test settings");
  await page.getByRole("button", { name: `Open ${name}`, exact: true }).click();
  await expect(nav.getByRole("button", { name: /^2\. Test settings/ })).toHaveAttribute("aria-current", "step");
  const noSource = `Workflow empty ${Date.now()}`;
  await page.getByLabel("New experiment name").fill(noSource);
  await page.getByRole("button", { name: "Create experiment" }).click();
  await expect(nav.getByRole("button", { name: /^1\. Documents/ })).toHaveAttribute("aria-current", "step");
  await expect(page.getByLabel("Next action")).toContainText("Add and save");
});
