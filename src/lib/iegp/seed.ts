const AT = "2026-09-10T12:00:00.000Z";

function lock(
  name: string,
  fn: ActorFunction,
  note?: string,
  at = AT,
): Lock {
  return {
    locked: true,
    actor_name: name,
    actor_function: fn,
    locked_at: at,
    note: note ?? null,
  };
}

function dims(
  values: Partial<Record<CoverageDimension, DimensionValue>>,
  rationale: string,
  who: [string, ActorFunction],
): Record<CoverageDimension, DimensionAssessment> {
  const base = emptyDimensions();
  for (const [k, v] of Object.entries(values) as [CoverageDimension, DimensionValue][]) {
    base[k] = {
      value: v,
      rationale,
      lock: lock(who[0], who[1], rationale),
    };
  }
  return base;
}

function coverage(args: {
  id: string;
  gap_id: string;
  tactic_id: string;
  overall: OverallCoverage;
  rationale: string;
  values: Partial<Record<CoverageDimension, DimensionValue>>;
  who: [string, ActorFunction];
  stale?: boolean;
}) {
  return {
    id: args.id,
    gap_id: args.gap_id,
    tactic_id: args.tactic_id,
    dimensions: dims(args.values, args.rationale, args.who),
    overall: args.overall,
    overall_rationale: args.rationale,
    overall_lock: lock(args.who[0], args.who[1], args.rationale),
    stale: args.stale ?? false,
    needs_review: false,
  };
}

function blocks(
  source_id: string,
  rows: { heading: string; text: string; location: string }[],
): SourceBlock[] {
  return rows.map((r, i) => ({
    id: `${source_id}-B${String(i + 1).padStart(2, "0")}`,
    source_id,
    ...r,
  }));
}

