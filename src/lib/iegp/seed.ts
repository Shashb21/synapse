function need(
  id: string,
  n: {
    statement: string;
    domain: import("./enums").EvidenceDomain;
    stakeholder: ActorFunction;
    objective_id: string;
    decision_supported: string;
    geography: string;
    population: string;
    intervention: string;
    comparator: string;
    outcome: string;
    timing: string;
    source_id: string;
    source_quote: string;
    status: "candidate" | "accepted" | "rejected";
    who: [string, ActorFunction] | null;
  },
) {
  const { who, ...rest } = n;
  return {
    id,
    ...rest,
    confidence: n.status === "candidate" ? 0.55 : 0.86,
    status_lock: who ? lock(...who) : unlocked(),
  };
}

