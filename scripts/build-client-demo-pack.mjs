// Regenerates src/lib/demo/client-pack.ts from the .txt files in src/lib/demo/client-pack/ (KAN-138).
// Run after editing a document: node scripts/build-client-demo-pack.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "src/lib/demo/client-pack");
const META = [
  ["payer-hta-interviews", "01-payer-hta-stakeholder-interviews.txt", "Payer and HTA stakeholder interviews", "stakeholder_interview", "market_access"],
  ["kol-advisory-board", "02-medical-kol-advisory-board-report.txt", "Medical KOL advisory board report", "advisory_board", "medical_affairs"],
  ["targeted-literature-review", "03-targeted-literature-review.txt", "Targeted literature review", "targeted_literature_review", "heor"],
  ["clinical-development-plan", "04-clinical-development-plan-excerpt.txt", "Clinical development plan (excerpt)", "clinical_development_plan", "clinical_development"],
  ["rwe-strategy", "05-real-world-evidence-strategy.txt", "Real-world evidence strategy 2026-2028", "rwe_strategy", "rwe"],
  ["medical-action-plan", "06-medical-action-plan-2027.txt", "Medical action plan 2027", "medical_strategy", "medical_affairs"],
  ["field-medical-insights", "07-field-medical-insights-report.txt", "Field medical insights report Q3 2026", "other_internal", "medical_affairs"],
];

const entries = META.map(([id, filename, title, source_type, stakeholder_function]) => {
  const text = readFileSync(path.join(dir, filename), "utf8").replace(/\r\n/g, "\n").trimEnd();
  return `  {\n    id: ${JSON.stringify(id)},\n    filename: ${JSON.stringify(filename)},\n    title: ${JSON.stringify(title)},\n    source_type: ${JSON.stringify(source_type)},\n    stakeholder_function: ${JSON.stringify(stakeholder_function)},\n    text: ${JSON.stringify(text)},\n  },`;
});

writeFileSync(
  path.join(process.cwd(), "src/lib/demo/client-pack.ts"),
  `// Generated by scripts/build-client-demo-pack.mjs from src/lib/demo/client-pack/*.txt. Do not edit by hand.
import type { DemoSourceFile } from "@/lib/iegp/demo-pack";

/**
 * The client demo's input documents (KAN-138): seven full-length, fictional
 * Velmara planning documents. The demo workspace accepts only these, and
 * "Download demo files" serves them. The short DEMO_PACK stays for the tests,
 * harness and gold evals.
 */
export const CLIENT_DEMO_PACK: DemoSourceFile[] = [
${entries.join("\n")}
];
`,
);
console.log(`Wrote ${entries.length} documents.`);
